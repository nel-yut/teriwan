/** 次にやることのヒント(イリス) */
export function hintFor(flag: (k: string) => boolean | number, rank: number): string {
  if (!flag('introDone')) return '最初の相棒を選びましょう。';
  if (!flag('gate01Clear')) return '「芽吹きの門」を探索して、ボスを倒してみて。肉を投げると幻獣が仲間になりやすいわ。';
  if (rank < 1) return '星冠競技場の「見習い」大会に挑戦してみて。優勝すると風鈴の門が開くわ。';
  if (!flag('gate02Clear')) return '「風鈴の門」の最奥で鐘を鳴らしましょう。';
  if (rank < 2) return '競技場の「青銅」大会へ。優勝すると配合堂が使えて、潮騒・鉄屑の門も開くわ。';
  if (!flag('gate04Clear')) return '配合で新しい幻獣を作りながら、潮騒・鉄屑の門を進みましょう。♂と♀、Lv10以上が必要よ。';
  if (rank < 3) return '「白銀」大会に挑戦。炎脈・白凪の門が開くわ。';
  if (!flag('gate06Clear')) return '炎脈の門と白凪の門を攻略して、「黄金」大会を目指しましょう。';
  if (rank < 4) return '「黄金」大会に挑戦して、朧影・星環の門を開きましょう。';
  if (!flag('gate08Clear')) return '朧影の門と星環の門を攻略して、八つの調律核を揃えて。';
  if (rank < 5) return 'いよいよ星冠杯ね。準備ができたら競技場へ!';
  return '全部の幻獣を集めて、図鑑を完成させてみましょう。配合の組み合わせは無限大よ!';
}
